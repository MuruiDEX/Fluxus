"""Brief — Team-Lead intake record (Stage 8.1, contract §1).

One row per goal submission. Questions are generated by the Team-Lead LLM
and stored only after passing validation; answers/summary/project linkage
land in later phases (8.2+). Status covers the full lifecycle up front so
later phases never need a constraint migration for new states.
"""

from sqlalchemy import JSON, ForeignKey, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.persistence.base import ID_LEN, Base, BusinessScopedMixin, IdMixin, TimestampMixin
from app.persistence.enums import BriefStatus, literal_check


class Brief(BusinessScopedMixin, IdMixin, TimestampMixin, Base):
    __tablename__ = "briefs"
    __table_args__ = (literal_check("status", BriefStatus, "ck_briefs_status"),)

    business_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("businesses.id", ondelete="CASCADE"), index=True
    )
    project_id: Mapped[str | None] = mapped_column(
        String(ID_LEN), ForeignKey("projects.id", ondelete="SET NULL"), nullable=True
    )
    goal: Mapped[str] = mapped_column(Text)
    questions: Mapped[list] = mapped_column(JSON, default=list)
    answers: Mapped[list] = mapped_column(JSON, default=list)
    summary: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    status: Mapped[str] = mapped_column(String(32), default=BriefStatus.DRAFT.value)
